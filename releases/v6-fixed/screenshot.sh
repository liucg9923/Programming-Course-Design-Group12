#!/bin/bash
# 一键自动化截图脚本
# 1. 重置数据到初始状态
# 2. 编译
# 3. 启动 expect 自动驱动程序到 4 个截图点
# 用户只需在每个截图点按 Cmd+Shift+4 截图，截完按 Enter 进入下一截图点

set -e

cd "$(dirname "$0")"
echo "=========================================="
echo "  HIS 自动化截图脚本"
echo "=========================================="

# ----- 第 1 步：重置数据到干净状态 -----
echo ""
echo "[1/3] 重置数据..."

# 1.1 还原静态数据（doctor / medicine / patient / record / system_state）
INIT="_initial_data"
mkdir -p "$INIT"
for f in patient.txt medicine.txt record.txt system_state.txt doctor.txt; do
    # 第一次运行时备份；之后每次从备份还原
    if [ ! -f "$INIT/$f" ]; then
        cp "$f" "$INIT/$f"
    else
        cp "$INIT/$f" "$f"
    fi
done

# 1.2 重新生成纯净的 30 条住院数据 + 床位状态（避免污染）
python3 - <<'PYEOF'
beds = [
    (1, 101, 20000, "内科"), (1, 102, 20000, "内科"),
    (1, 103, 20000, "内科"), (1, 104, 20000, "内科"),
    (2, 201, 20000, "外科"), (2, 202, 20000, "外科"),
    (2, 203, 20000, "外科"), (2, 204, 20000, "外科"),
    (3, 301, 50000, "急诊科"), (3, 302, 50000, "急诊科"),
    (3, 303, 50000, "急诊科"), (3, 304, 50000, "急诊科"),
    (4, 401, 80000, "内科"), (4, 402, 80000, "内科"),
    (4, 403, 80000, "外科"), (4, 404, 80000, "外科"),
    (5, 501, 20000, "儿科"), (5, 502, 20000, "儿科"),
    (5, 503, 20000, "儿科"), (5, 504, 20000, "儿科"),
    (6, 601, 20000, "骨科"), (6, 602, 20000, "骨科"),
    (6, 603, 20000, "骨科"), (6, 604, 20000, "骨科"),
    (7, 701, 20000, "妇产科"), (7, 702, 20000, "妇产科"),
    (7, 703, 80000, "妇产科"), (7, 704, 80000, "妇产科"),
    (8, 801, 20000, "心内科"), (8, 802, 20000, "心内科"),
]
docs = {"内科":1001,"外科":1002,"儿科":1003,"急诊科":1004,
        "妇产科":1005,"骨科":1011,"心内科":1012,"呼吸内科":1015}

# 写 inpatient.txt（不包含 803/804/8 病房，留给脚本测试用）
with open("inpatient.txt", "w") as f:
    for i, (w, b, fee, dept) in enumerate(beds):
        pid = 2001 + i
        did = docs.get(dept, 1001)
        days_total = 5 + (i % 6)
        deposit_yuan = max(200 * days_total, 1500 + i * 100)
        deposit_yuan = (deposit_yuan + 99) // 100 * 100
        deposit_cents = deposit_yuan * 100
        days_stayed = 3
        charged = fee * days_stayed
        balance = deposit_cents - charged
        f.write(f"{pid}\t{did}\t{w}\t{b}\t{deposit_cents}\t{balance}\t{fee}\t{charged}\t20260420\t20260422\t{9+(i%8)}\t{days_total}\t{days_stayed}\t1\t0\n")

# 写 ward_bed.txt（同步把这 30 张床位标为占用）
inp = {(1,101):2001,(1,102):2002,(1,103):2003,(1,104):2004,
       (2,201):2005,(2,202):2006,(2,203):2007,(2,204):2008,
       (3,301):2009,(3,302):2010,(3,303):2011,(3,304):2012,
       (4,401):2013,(4,402):2014,(4,403):2015,(4,404):2016,
       (5,501):2017,(5,502):2018,(5,503):2019,(5,504):2020,
       (6,601):2021,(6,602):2022,(6,603):2023,(6,604):2024,
       (7,701):2025,(7,702):2026,(7,703):2027,(7,704):2028,
       (8,801):2029,(8,802):2030}
# 静态病房表：8 个病房 4 张床
ward_data = [
    (1,101,1,"内科"),(1,102,1,"内科"),(1,103,1,"内科"),(1,104,1,"内科"),
    (2,201,1,"外科"),(2,202,1,"外科"),(2,203,1,"外科"),(2,204,1,"外科"),
    (3,301,2,"急诊科"),(3,302,2,"急诊科"),(3,303,2,"急诊科"),(3,304,2,"急诊科"),
    (4,401,3,"内科"),(4,402,3,"内科"),(4,403,3,"外科"),(4,404,3,"外科"),
    (5,501,1,"儿科"),(5,502,1,"儿科"),(5,503,1,"儿科"),(5,504,1,"儿科"),
    (6,601,1,"骨科"),(6,602,1,"骨科"),(6,603,1,"骨科"),(6,604,1,"骨科"),
    (7,701,1,"妇产科"),(7,702,1,"妇产科"),(7,703,3,"妇产科"),(7,704,3,"妇产科"),
    (8,801,1,"心内科"),(8,802,1,"心内科"),(8,803,1,"呼吸内科"),(8,804,1,"呼吸内科"),
]
with open("ward_bed.txt", "w") as f:
    for w, b, t, d in ward_data:
        if (w, b) in inp:
            f.write(f"{w}\t{b}\t{t}\t{d}\t1\t{inp[(w,b)]}\t0\n")
        else:
            f.write(f"{w}\t{b}\t{t}\t{d}\t0\t0\t0\n")
PYEOF

# 1.3 清空日志和动态文件
: > log_operation.txt
: > log_bad_data.txt
: > log_delete.txt
: > revenue.txt
: > money.txt

# 1.4 把 system_state.txt 改回到 4-23 12:42（确保每次起点一致）
echo "2101 101 1 43 0 - 20260423 12 42 3 0" > system_state.txt

echo "    数据已重置（30 名住院 + 803/804 留作测试床位）"

# ----- 第 2 步：编译 -----
echo ""
echo "[2/3] 编译 his..."
g++ -Wall -Wno-deprecated-declarations -Wno-missing-field-initializers \
    -o his *.cpp 2>&1 | head -10

if [ ! -f his ]; then
    echo "[错误] 编译失败"
    exit 1
fi
echo "    编译完成"

# ----- 第 3 步：启动 expect 自动化 -----
echo ""
echo "[3/3] 启动自动化截图..."
echo ""
echo "操作提示："
echo "  - 程序自动跑到每个截图点会停下"
echo "  - 屏幕上会出现 \"截图点 X / 4：xxx\""
echo "  - 此时按 Cmd+Shift+4 圈选区域截图"
echo "  - 截好后按 Enter 进入下一个截图点"
echo "  - 4 张截好后程序自动退出"
echo ""
echo "3 秒后开始..."
sleep 3
echo ""

expect ./screenshot.exp

echo ""
echo "=========================================="
echo "  完成！截图保存在桌面，文件名形如"
echo "  截屏 2026-XX-XX XX.XX.XX.png"
echo "=========================================="
